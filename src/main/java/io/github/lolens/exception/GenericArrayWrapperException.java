package io.github.lolens.exception;

public class GenericArrayWrapperException extends Exception {

  public GenericArrayWrapperException(String message) {
    super(message);
  }

  public GenericArrayWrapperException(String message, Throwable throwable) {
    super(message, throwable);
  }

  public GenericArrayWrapperException(Throwable throwable) {
    super(throwable);
  }




}
